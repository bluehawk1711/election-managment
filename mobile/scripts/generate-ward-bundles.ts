/**
 * Bundles the roll into the app: `assets/roll/ward-NN.json` + `wards.json`.
 *
 *     node scripts/generate-ward-bundles.ts     # Node ≥ 22.6 strips types
 *
 * This is the "0 latency" path: the roll ships *inside* the APK, so the
 * voters screen paints from data that is already resident on a first-ever
 * launch — no Firestore round trip, no cold-start fetch, no rules dependency
 * for the base roll. `lib/roll/bundled.ts` reads what this writes.
 *
 * Each row carries the Hindi roll fields **plus a romanised English copy**
 * (`nameEn`, `fatherOrHusbandNameEn`, `localityEn`) generated by
 * `lib/roll/romanize.ts`. Search indexes both: a Latin query matches the
 * English copy by plain substring (exact, stable) and the phonetic skeleton
 * from `translit.ts` remains the fuzzy fallback for either script. The copy
 * is regenerated from the CSVs by rerunning this script — it lives in the
 * repo, never in a database, so it cannot drift out of step with the source.
 *
 * Validation mirrors `scripts/seed-roll.mjs`: unknown labels, duplicate
 * serials and summary-count mismatches abort the run — a half-correct bundle
 * that ships to every device is worse than no bundle.
 *
 * CommonJS interop: `scripts/parse-csv.js` is the shared RFC-4180 reader, the
 * same one `__tests__/roll-import.test.ts` requires — one implementation, not
 * two.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { romanize, titleCase } from '../lib/roll/romanize.ts';

const require = createRequire(import.meta.url);
const { parseCsv } = require('./parse-csv.js') as {
  parseCsv: (text: string) => string[][];
};

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DATA_DIR = path.resolve(HERE, '../../data/rajasthan/jodhpur/jhanwar/veernagar');
const OUT_DIR = path.resolve(HERE, '../assets/roll');

/** `पुरूष` → `male`, exactly as the seeder maps them. */
const GENDER_BY_LABEL: Record<string, 'male' | 'female' | 'other'> = {
  'पुरूष': 'male',
  'स्त्री': 'female',
  'तृतीयलिंग': 'other',
};
const RELATION_BY_LABEL: Record<string, 'father' | 'husband' | 'mother' | 'other'> = {
  'पिता': 'father',
  'पति': 'husband',
  'माता': 'mother',
  'अन्य': 'other',
};

/** One row of `ward-NN.csv`, plus the generated English copy. */
interface BundledRow {
  id: string;
  wardNo: number;
  serialNo: number;
  epicId: string;
  name: string;
  relation: 'father' | 'husband' | 'mother' | 'other';
  relationLabel: string;
  fatherOrHusbandName: string;
  houseNo: string;
  age: number;
  gender: 'male' | 'female' | 'other';
  locality: string;
  pdfPage: number;
  /**
   * Present (`true`) only on the rows the photos PDF stamps DELETED — the
   * marker list in `data/rajasthan/jodhpur/jhanwar/veernagar/deleted.json`
   * (EXTRACTION.md §Step 8). Omitted everywhere else, so a non-deleted row
   * stays byte-for-byte what it was.
   */
  deleted?: boolean;
  nameEn: string;
  fatherOrHusbandNameEn: string;
  localityEn: string;
}

interface SummaryRow {
  wardNo: number;
  voters: number;
  male: number;
  female: number;
  thirdGender: number;
  delimitation: string;
  boothNo: number;
  roomNo: number;
  boothAddress: string;
  pdfPages: string;
}

/** `{ header, rows }` from a parsed CSV — same shape the seeder builds. */
function readCsvRows(text: string): { header: string[]; rows: string[][] } | null {
  const rows = parseCsv(text);
  if (!rows.length) return null;
  return { header: rows[0], rows: rows.slice(1) };
}

function headerIndex(header: string[], file: string): Map<string, number> {
  const index = new Map<string, number>();
  header.forEach((name, i) => index.set(name.trim(), i));
  if (!index.size) throw new Error(`${file}: empty header`);
  return index;
}

/**
 * `deleted.json` → voter id (`w{ward}-{serial}`) → the EPIC id the marker
 * was validated against.
 *
 * Written by `tools/extract_roll/deleted_flags.py` from the 106x76 DELETED
 * stamps drawn over record cells in `data/VeerNagar-photos.pdf`. A missing or
 * internally inconsistent file aborts the run: a bundle that silently drops
 * the deleted flag is worse than no bundle, because both apps render the
 * badge straight off this field.
 */
function readDeletedFlags(): Map<string, string> {
  const file = path.join(DATA_DIR, 'deleted.json');
  if (!existsSync(file)) throw new Error(`Missing ${file}`);

  const parsed = JSON.parse(readFileSync(file, 'utf8')) as {
    count?: number;
    records?: { ward: number; serial: number; epic_id: string }[];
  };
  const records = parsed.records ?? [];
  if (!records.length) throw new Error(`${file}: no records`);
  if (parsed.count !== records.length) {
    throw new Error(`${file}: count ${parsed.count} vs ${records.length} records`);
  }

  const byId = new Map<string, string>();
  for (const record of records) {
    const id = `w${record.ward}-${record.serial}`;
    if (byId.has(id)) throw new Error(`${file}: duplicate marker for ${id}`);
    byId.set(id, record.epic_id);
  }
  return byId;
}

function readWardFile(
  wardNo: number,
  deleted: ReadonlyMap<string, string>,
  consumed: Set<string>
): BundledRow[] {
  const file = path.join(DATA_DIR, `ward-${String(wardNo).padStart(2, '0')}.csv`);
  if (!existsSync(file)) throw new Error(`Missing ${file}`);

  const parsed = readCsvRows(readFileSync(file, 'utf8'));
  if (!parsed) throw new Error(`${file} is empty`);

  const col = headerIndex(parsed.header, file);
  const required = [
    'serial_no', 'epic_id', 'name', 'relation', 'father_or_husband_name',
    'house_no', 'age', 'gender', 'locality', 'pdf_page',
  ];
  const problems: string[] = [];
  for (const name of required) {
    if (!col.has(name)) problems.push(`${file}: missing column "${name}"`);
  }
  if (problems.length) throw new Error(`\n  - ${problems.join('\n  - ')}`);

  const voters: BundledRow[] = [];

  parsed.rows.forEach((row, index) => {
    const lineNo = index + 2;
    const at = (name: string): string => (row[col.get(name) ?? -1] ?? '').trim();

    const serialNo = Number(at('serial_no'));
    const age = Number(at('age'));
    const pdfPage = Number(at('pdf_page'));
    const genderLabel = at('gender');
    const relationLabel = at('relation');
    const name = at('name');
    const father = at('father_or_husband_name');
    const locality = at('locality');

    if (!Number.isInteger(serialNo) || serialNo <= 0) {
      problems.push(`ward-${wardNo} line ${lineNo}: bad serial_no "${at('serial_no')}"`);
    }
    if (!Number.isInteger(age) || age < 0) {
      problems.push(`ward-${wardNo} line ${lineNo}: bad age "${at('age')}"`);
    }
    if (!Number.isInteger(pdfPage)) {
      problems.push(`ward-${wardNo} line ${lineNo}: bad pdf_page "${at('pdf_page')}"`);
    }
    const gender = GENDER_BY_LABEL[genderLabel];
    if (!gender) {
      problems.push(`ward-${wardNo} line ${lineNo}: unknown gender "${genderLabel}"`);
    }
    const relation = RELATION_BY_LABEL[relationLabel];
    if (!relation) {
      problems.push(`ward-${wardNo} line ${lineNo}: unknown relation "${relationLabel}"`);
    }
    if (row.length !== parsed.header.length) {
      problems.push(
        `ward-${wardNo} line ${lineNo}: ${row.length} fields, header has ${parsed.header.length}`
      );
    }
    if (problems.length > 20) return;

    const id = `w${wardNo}-${serialNo}`;
    const markedEpic = deleted.get(id);
    if (markedEpic !== undefined) {
      // The marker and the row must agree on WHO was struck — the flag
      // carries no epic of its own, so a mismatch here would badge the
      // wrong voter.
      if (markedEpic !== at('epic_id')) {
        problems.push(
          `ward-${wardNo} line ${lineNo}: deleted.json says ${markedEpic}, ` +
            `row has "${at('epic_id')}"`
        );
      } else {
        consumed.add(id);
      }
    }

    voters.push({
      id,
      wardNo,
      serialNo,
      epicId: at('epic_id'),
      name,
      relation,
      relationLabel: relationLabel || 'पिता',
      fatherOrHusbandName: father,
      houseNo: at('house_no'),
      age: Number.isFinite(age) ? age : 0,
      gender: gender ?? 'male',
      locality,
      pdfPage: Number.isFinite(pdfPage) ? pdfPage : 0,
      // Omitted (not `false`) on every non-marked row — see BundledRow. A
      // wrong epic above already threw by the time this would be written.
      ...(markedEpic !== undefined ? { deleted: true } : {}),
      // The English copy: romanised, title-cased, regenerated from the CSV
      // above — never edited by hand, never stored anywhere but here.
      nameEn: titleCase(romanize(name)),
      fatherOrHusbandNameEn: titleCase(romanize(father)),
      localityEn: titleCase(romanize(locality)),
    });
  });

  if (problems.length) {
    throw new Error(`\n  - ${problems.slice(0, 20).join('\n  - ')}`);
  }

  const ids = new Set(voters.map((voter) => voter.id));
  if (ids.size !== voters.length) {
    throw new Error(`ward-${wardNo}: ${voters.length - ids.size} duplicate serial_no`);
  }

  return voters;
}

function readSummary(): SummaryRow[] {
  const file = path.join(DATA_DIR, 'wards-summary.csv');
  if (!existsSync(file)) throw new Error(`Missing ${file}`);

  const parsed = readCsvRows(readFileSync(file, 'utf8'));
  if (!parsed) throw new Error(`${file} is empty`);

  const col = headerIndex(parsed.header, file);
  const at = (row: string[], name: string): string => (row[col.get(name) ?? -1] ?? '').trim();

  return parsed.rows.map((row) => ({
    wardNo: Number(at(row, 'ward_no')),
    voters: Number(at(row, 'voters')),
    male: Number(at(row, 'male')),
    female: Number(at(row, 'female')),
    thirdGender: Number(at(row, 'third_gender')),
    delimitation: at(row, 'ward_delimitation'),
    boothNo: Number(at(row, 'booth_no')),
    roomNo: Number(at(row, 'room_no')),
    boothAddress: at(row, 'booth_address'),
    pdfPages: at(row, 'pdf_pages'),
  }));
}

/** Stable, readable JSON: 2-space indent, trailing newline, LF. */
function writeJson(file: string, value: unknown): void {
  writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

function main(): void {
  const summary = readSummary().sort((a, b) => a.wardNo - b.wardNo);
  if (!summary.length) throw new Error('wards-summary.csv has no rows');

  mkdirSync(OUT_DIR, { recursive: true });

  let totalVoters = 0;
  const tally = { male: 0, female: 0, other: 0 };

  // EXTRACTION.md §Step 8 — the DELETED stamps lifted from the photos PDF.
  const deleted = readDeletedFlags();
  const consumedDeleted = new Set<string>();
  let deletedRows = 0;

  for (const ward of summary) {
    const voters = readWardFile(ward.wardNo, deleted, consumedDeleted);
    deletedRows += voters.filter((voter) => voter.deleted).length;

    // The summary is the ground truth the PDF extraction was checked
    // against; a mismatch here means the CSVs changed under us.
    if (voters.length !== ward.voters) {
      throw new Error(
        `ward ${ward.wardNo}: ${voters.length} rows, summary says ${ward.voters}`
      );
    }
    const counts = { male: 0, female: 0, other: 0 };
    for (const voter of voters) counts[voter.gender] += 1;
    if (counts.male !== ward.male || counts.female !== ward.female || counts.other !== ward.thirdGender) {
      throw new Error(
        `ward ${ward.wardNo}: gender tally ${JSON.stringify(counts)} vs summary ` +
          `${JSON.stringify({ male: ward.male, female: ward.female, other: ward.thirdGender })}`
      );
    }

    const file = path.join(OUT_DIR, `ward-${String(ward.wardNo).padStart(2, '0')}.json`);
    writeJson(file, { wardNo: ward.wardNo, voters });

    totalVoters += voters.length;
    tally.male += counts.male;
    tally.female += counts.female;
    tally.other += counts.other;

    console.log(
      `ward ${String(ward.wardNo).padStart(2, '0')}: ${voters.length} rows -> ${path.relative(process.cwd(), file)}`
    );
  }

  // Every marker must have found its row: a stale entry means the CSVs and
  // the marker list disagree about who exists.
  const orphaned = [...deleted.keys()].filter((id) => !consumedDeleted.has(id));
  if (orphaned.length) {
    throw new Error(
      `deleted.json: ${orphaned.length} marker(s) with no matching row: ` +
        orphaned.slice(0, 10).join(', ')
    );
  }
  console.log(`deleted flags: ${deletedRows}/${deleted.size} rows marked`);

  writeJson(path.join(OUT_DIR, 'wards.json'), {
    generatedAt: new Date().toISOString(),
    source: 'bundle',
    total: totalVoters,
    tally,
    wards: summary.map((ward) => ({
      wardNo: ward.wardNo,
      voterCount: ward.voters,
      male: ward.male,
      female: ward.female,
      thirdGender: ward.thirdGender,
      delimitation: ward.delimitation,
      boothNo: ward.boothNo,
      roomNo: ward.roomNo,
      boothAddress: ward.boothAddress,
      pdfPages: ward.pdfPages,
    })),
  });

  console.log(
    `\nbundled ${totalVoters} voters across ${summary.length} wards ` +
      `(m ${tally.male} / f ${tally.female} / o ${tally.other})`
  );
}

try {
  main();
} catch (error) {
  console.error(`\n✖ Bundle generation failed: ${(error as Error).message}`);
  process.exit(1);
}
