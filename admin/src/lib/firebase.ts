/**
 * The panel's Firebase client — the web SDK pointed at the SAME project,
 * database and rules the mobile app uses.
 *
 * Two details are copied from `mobile/lib/firebase.ts` on purpose and must
 * not drift:
 *
 * 1. **The database id is `default`, not `(default)`.** The project was
 *    provisioned as ENTERPRISE with an explicitly named database. The SDK's
 *    implicit `'(default)'` resolves to `5 NOT_FOUND: no such database`
 *    against this project while the console happily shows collections.
 * 2. **Env names are `NEXT_PUBLIC_*`** instead of `EXPO_PUBLIC_*` — same six
 *    values; `.env.local` is generated by prefixing the mobile's `.env`.
 *
 * Client-only module: every import of this file happens from `'use client'`
 * code, so auth never runs during a server render.
 */
import { getApps, initializeApp, type FirebaseApp } from 'firebase/app';
import { connectAuthEmulator, getAuth, type Auth } from 'firebase/auth';
import { initializeFirestore } from 'firebase/firestore';
import {
  connectFirestoreEmulator,
  getFirestore,
  type Firestore,
} from 'firebase/firestore';
import {
  getDatabase,
  connectDatabaseEmulator,
  type Database,
} from 'firebase/database';

/** See the file header — enterprise-named database, never `(default)`. */
export const FIRESTORE_DATABASE_ID = 'default';

const firebaseConfig = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY,
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN,
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID,
  storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID,
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID,
};

if (!firebaseConfig.apiKey || !firebaseConfig.projectId) {
  throw new Error(
    'Missing Firebase environment variables. Copy .env.example (or the mobile ' +
      'app\'s .env) into admin/.env.local with the NEXT_PUBLIC_FIREBASE_* names.'
  );
}

// Guards against double-init when Fast Refresh re-executes the module.
const existing = getApps()[0];
export const app: FirebaseApp = existing ?? initializeApp(firebaseConfig);

/**
 * `getAuth(app)` uses `browserLocalPersistence` on the web automatically, so
 * a signed-in admin survives reloads without any of React Native's
 * persistence gymnastics from the mobile file.
 */
export const auth: Auth = getAuth(app);

/**
 * Database id passed explicitly — see FIRESTORE_DATABASE_ID. Long-polling
 * auto-detect kept from the mobile client; a browser behind a stubborn
 * corporate proxy graces down to it instead of failing the page.
 *
 * `initializeFirestore` rather than `getFirestore` + settings so the
 * settings land on a fresh instance — on a Fast Refresh re-run the
 * existing instance would throw "settings can no longer be changed".
 */
export const db: Firestore = existing
  ? getFirestore(app, FIRESTORE_DATABASE_ID)
  : initializeFirestore(
      app,
      { experimentalAutoDetectLongPolling: true },
      FIRESTORE_DATABASE_ID
    );

/**
 * Realtime Database instance for the panel.
 * Shares the same app as Firestore but uses the databaseURL from env.
 * The database id is `default`, NOT `(default)`.
 */
export const database: Database | null = existing
  ? getDatabase(app, FIRESTORE_DATABASE_ID)
  : initializeDatabase(
      app,
      { databaseURL: process.env.NEXT_PUBLIC_FIREBASE_DATABASE_URL },
      FIRESTORE_DATABASE_ID
    );

/**
 * Point at the local emulators when NEXT_PUBLIC_FIREBASE_USE_EMULATOR=1
 * (`npm run emulators` in mobile/ starts them). Gated on `!existing` because
 * `connect*Emulator` throws once the instance has made a request, which a
 * Fast Refresh re-run would have done.
 */
if (
  !existing &&
  typeof window !== 'undefined' &&
  process.env.NEXT_PUBLIC_FIREBASE_USE_EMULATOR === '1'
) {
  connectAuthEmulator(auth, 'http://localhost:9099', { disableWarnings: true });
  connectDatabaseEmulator(database, 'localhost', 9000);
  console.log('[firebase] using emulators at localhost');
}