/**
 * The voter-roll data model in the panel — the base half of
 * `mobile/lib/roll/types.ts`, ported so `search.ts` / `translit.ts` compile
 * here byte-for-byte the same.
 *
 * Same split as mobile: **base** (the imported roll, read-only, byte-identical
 * to the CSVs the PDF extraction produced) and **overlay** (what a user may
 * add or change). The panel's roll page reads the BUNDLED base rows served
 * from `public/roll/*.json` — no Firestore, no rules dependency, which is
 * exactly why the roll can appear in the panel at all (the old `/voters`
 * redirect existed because `voters/$id` has no collection-level read; static
 * JSON sidesteps that entirely).
 *
 * The overlay half here is a slim shape: enough for `search.ts` to key the
 * fields a team edit may add (phone / jati / support / leaning / note), and
 * `updatedAt` — which is also the cache guard: an `undefined` updatedAt means
 * "never edited", i.e. the row is a pure function of the bundled JSON and its
 * search key can be memoised.
 */

/** One row of `ward-NN.json`, as imported. Field names mirror the CSV. */
export interface RollVoter {
  /** `w{wardNo}-{serialNo}` — stable, human-debuggable. */
  id: string;
  wardNo: number;
  /** The roll's printed serial, 1..N within the ward. */
  serialNo: number;
  /** EPIC / elector id exactly as printed. */
  epicId: string;
  name: string;
  relation: Relation;
  /** The label as printed (`पिता` / `पति` / …), kept for traceability. */
  relationLabel: string;
  fatherOrHusbandName: string;
  /** Free-form on the roll: `0`, `44`, `33 बी`, `मकान 84`, … */
  houseNo: string;
  age: number;
  gender: Gender;
  locality: string;
  /** The PDF page this row came from — lets anyone open the source. */
  pdfPage: number;
  /**
   * Romanised copies of the three Hindi fields — generated by mobile's
   * `scripts/generate-ward-bundles.ts` and shipped inside the same JSON, so
   * the panel gets both scripts for free: `ramesh` finds `Ramesh Kumar` by
   * plain substring, ranked above the phonetic hits.
   */
  nameEn?: string;
  fatherOrHusbandNameEn?: string;
  localityEn?: string;
}

export type Gender = 'male' | 'female' | 'other';
export type Relation = 'father' | 'husband' | 'mother' | 'other';

/** One entry of the `wards.json` summary — booth facts live here. */
export interface WardMeta {
  wardNo: number;
  voterCount: number;
  male: number;
  female: number;
  thirdGender: number;
  delimitation: string;
  boothNo: number;
  roomNo: number;
  boothAddress: string;
  /** Record-page range as printed on the cover, e.g. `3-28`. */
  pdfPages: string;
}

/** The shape of `public/roll/wards.json`. */
export interface WardsBundle {
  generatedAt: string;
  source: string;
  total: number;
  tally: { male: number; female: number; other: number };
  wards: WardMeta[];
}

/**
 * The subset of `VoterOverlay` the panel's roll layer knows about — the
 * fields a team edit may carry into the search index. Bookkeeping
 * (`updatedAt`) doubles as the "has this row ever been edited" guard.
 */
export interface VoterOverlay {
  /** Corrections to roll fields — present only when edited. */
  name?: string;
  fatherOrHusbandName?: string;
  houseNo?: string;
  age?: number;
  gender?: Gender;
  locality?: string;
  phone?: string;
  jati?: string;
  support?: string;
  leaning?: string;
  leaningNote?: string;
  note?: string;
  updatedAt?: number;
  updatedBy?: string;
}

/**
 * `RollVoter` ⨯ `VoterOverlay` — what the list and the slip render.
 *
 * The bundled rows arrive overlay-less, so `viewOf` fills `overlay` with an
 * empty object and derives `effective` straight from the base row. When a
 * page later merges Firestore `voterEdits`, only `viewOf`'s inputs change;
 * every consumer keeps its shape.
 */
export interface VoterView extends RollVoter {
  overlay: VoterOverlay;
  /** Effective values: overlay wins over the base row. */
  effective: {
    name: string;
    fatherOrHusbandName: string;
    houseNo: string;
    age: number;
    gender: Gender;
    locality: string;
    phone: string;
    jati: string;
  };
  photoUrl: string | null;
}

/** Bundled base row → the view shape every screen renders. */
export function viewOf(voter: RollVoter, overlay: VoterOverlay = {}): VoterView {
  return {
    ...voter,
    overlay,
    effective: {
      name: overlay.name ?? voter.name,
      fatherOrHusbandName: overlay.fatherOrHusbandName ?? voter.fatherOrHusbandName,
      houseNo: overlay.houseNo ?? voter.houseNo,
      age: overlay.age ?? voter.age,
      gender: overlay.gender ?? voter.gender,
      locality: overlay.locality ?? voter.locality,
      phone: overlay.phone ?? '',
      jati: overlay.jati ?? '',
    },
    photoUrl: null,
  };
}

/** हिन्दी labels for the enum values — the roll and the slip are Hindi-first. */
export const GENDER_LABELS: Record<Gender, string> = {
  male: 'पुरुष',
  female: 'महिला',
  other: 'अन्य',
};

/** The gender word as it prints on the slip: "35 वर्ष / पुरुष". */
export function genderLabel(gender: Gender): string {
  return GENDER_LABELS[gender] ?? '—';
}
