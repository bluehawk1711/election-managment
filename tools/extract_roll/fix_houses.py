# -*- coding: utf-8 -*-
"""House-number repair for ward CSVs.

Rule (per the user's latest message):
  * The printed house number is almost always a digit string ("34", "354",
    "k-54", "102", "3-57", …), so the raw text layer and the OCR layer both
    give digits in the vast majority of rows.
  * When the raw layer gives a *numeric* lookalike that the OCR produced as a
    non-digit (e.g. raw "128", OCR "2८" or "28"), the raw digit wins.
  * When a raw token looks like a true multi-digit number (e.g. raw "35",
    OCR "35") → adopt the digit string, trim separators.
  * When a raw token is a genuine digit string ("354") → adopt it and trim.
  * Anything else (colony/plot text, junk glyph runs, stray letters) →
    keep it EMPTY. "if data isn't correct but there is a number 43 or 34
    use those instead" only applies to the third clause.
  * If a row has no number at all in house_no → record has no house number,
    keep it empty; delete "no number" markers such as "0".

Clip every house cell at 300 dpi, upsample 3x, OCR with hin+eng, then take
the longest contiguous digit run (which naturally kills stray garbage like
"25", "5", "43", "34" that appear around the real number: the longest run is
the actual number).
"""
import csv
import json
import os
import re
import subprocess
import sys
from PIL import Image

BASE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(BASE, '..', '..', 'data', 'rajasthan',
                    'jodhpur', 'jhanwar', 'veernagar')
TTS = r'C:\Program Files\Tesseract-OCR\tesseract.exe'

# 300 dpi number cells, already generated by the extract pipeline
CELL_DIR = os.path.join(BASE, 'ocr_cells')


def longest_run(tok):
    """Longest contiguous digit run in a token ('' when none)."""
    runs = re.findall(r'\d+', tok)
    return max(runs, key=len) if runs else ''


def ocr_cell(img_path, dpi_scale=3):
    """OCR one house cell, return (best_run, raw_joined).

    `best_run` is the longest contiguous digit run in the OCR output.
    """
    im = Image.open(img_path).convert('RGB')
    im = im.resize((im.width * dpi_scale, im.height * dpi_scale),
                   Image.LANCZOS)
    tmp = img_path + '.tmp.png'
    im.save(tmp)
    try:
        out = subprocess.run(
            [TTS, tmp, os.path.dirname(img_path), '-l', 'hin+eng',
             '--psm', '7'],
            capture_output=True, text=True, timeout=60)
        txt = out.stdout.strip()
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)
    words = re.findall(r'[A-Za-z\u0900-\u097F0-9]+', txt)
    cands = [w for w in words if re.search(r'\d', w)]
    best_run = ''
    if cands:
        best_run = max(cands, key=lambda w: len(longest_run(w)))
    return longest_run(best_run), ' '.join(words)


def fix_ward_csv(ward, path, counter):
    with open(path, encoding='utf-8-sig', newline='') as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        key = r['serial_no']
        h = r['house_no'] or ''
        if re.fullmatch(r'\d{1,6}', h):
            continue  # already numeric: raw layer proved exact
        img = os.path.join(CELL_DIR, 'w%02d_p%04d_s%04d_house.png' % (
            ward, int(r['pdf_page']), int(key)))
        if not os.path.exists(img):
            counter['missing_cells'] += 1
            continue
        run, _joined = ocr_cell(img)
        new = run  # numeric run wins; '' when OCR found no digits
        if h != new:
            counter['fixed'] += 1
            r['house_no'] = new
    with open(path, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    return counter


def main():
    counter = {'fixed': 0, 'missing_cells': 0}
    for w in range(1, 14):
        path = os.path.join(DATA, 'ward-%02d.csv' % w)
        if not os.path.exists(path):
            continue
        c = fix_ward_csv(w, path, counter)
        counter['fixed'] += c['fixed']
        counter['missing_cells'] += c['missing_cells']
        print('ward %02d: %d fixed, %d missing cells' % (
            w, c['fixed'], c['missing_cells']))
    print('TOTAL fixed=%d missing_cells=%d' % (
        counter['fixed'], counter['missing_cells']))
    json.dump(counter, open(os.path.join(BASE, 'house_fix_counts.json'),
                           'w'), indent=1)


if __name__ == '__main__':
    main()
